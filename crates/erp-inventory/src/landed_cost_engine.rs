//! Integrated Landed Cost Engine & GL Balancing (`erp-inventory::landed_cost_engine`).
//!
//! Implements Phase 4 Landed Cost Voucher allocation:
//! - Distributes import duties, freight, insurance by Quantity or Valuation Amount
//! - Adjusts stock valuation layers (adding landed costs into layer rates)
//! - Generates balanced General Ledger accounting entries:
//!   * Debit Stock In Hand (Inventory Valuation)
//!   * Credit Expenses Included In Valuation (or custom landed expense account)

use compact_str::CompactString;
use rust_decimal::Decimal;
use serde::{Deserialize, Serialize};

use crate::landed_cost_voucher::LandedCostVoucher;

/// General Ledger Entry generated by Landed Cost allocation.
#[derive(Debug, Clone, Serialize, Deserialize, PartialEq, Eq)]
pub struct LandedCostGlEntry {
    pub posting_date: chrono::NaiveDate,
    pub account: CompactString,
    pub debit: Decimal,
    pub credit: Decimal,
    pub remarks: CompactString,
}

/// Valuation Layer Adjustment Descriptor.
#[derive(Debug, Clone, Serialize, Deserialize, PartialEq, Eq)]
pub struct ValuationLayerAdjustment {
    pub receipt_document: CompactString,
    pub item_code: CompactString,
    pub qty: Decimal,
    pub original_rate: Decimal,
    pub additional_allocated_charges: Decimal,
    pub adjusted_rate: Decimal,
}

/// Integrated Landed Cost Outcome including adjustments and balancing GL entries.
#[derive(Debug, Clone, Serialize, Deserialize, PartialEq, Eq)]
pub struct LandedCostAllocationOutcome {
    pub voucher_name: CompactString,
    pub total_allocated_charges: Decimal,
    pub layer_adjustments: Vec<ValuationLayerAdjustment>,
    pub gl_entries: Vec<LandedCostGlEntry>,
}

/// Integrated Landed Cost Engine.
pub struct LandedCostEngine;

impl LandedCostEngine {
    /// Allocates charges and generates exact balancing GL entries and layer adjustments.
    pub fn process_landed_cost(
        voucher: &mut LandedCostVoucher,
        posting_date: chrono::NaiveDate,
        stock_in_hand_account: &str,
    ) -> Result<LandedCostAllocationOutcome, &'static str> {
        voucher.allocate_charges()?;

        let total_charges: Decimal = voucher.charges.iter().map(|c| c.amount).sum();
        let mut layer_adjustments = Vec::with_capacity(voucher.items.len());

        for item in &voucher.items {
            layer_adjustments.push(ValuationLayerAdjustment {
                receipt_document: item.receipt_document.clone(),
                item_code: item.item_code.clone(),
                qty: item.qty,
                original_rate: item.original_rate,
                additional_allocated_charges: item.allocated_charges,
                adjusted_rate: item.landed_rate,
            });
        }

        let mut gl_entries = Vec::new();

        // 1. Debit Stock In Hand for the total added landed charges
        gl_entries.push(LandedCostGlEntry {
            posting_date,
            account: stock_in_hand_account.into(),
            debit: total_charges,
            credit: Decimal::ZERO,
            remarks: format!("Landed cost adjustment for voucher {}", voucher.name).into(),
        });

        // 2. Credit each charge expense account (e.g. Customs Duties, Freight, Insurance)
        for charge in &voucher.charges {
            gl_entries.push(LandedCostGlEntry {
                posting_date,
                account: charge.expense_account.clone(),
                debit: Decimal::ZERO,
                credit: charge.amount,
                remarks: format!("{}: {}", voucher.name, charge.description).into(),
            });
        }

        Ok(LandedCostAllocationOutcome {
            voucher_name: voucher.name.clone(),
            total_allocated_charges: total_charges,
            layer_adjustments,
            gl_entries,
        })
    }
}
