//! High-Level Audio Streaming, Subsonic v1.16 Protocol, Soundboards, Radio, and DSP Filter routes.

use super::*;
use actix_web::web;

/// Configures all Audio Streaming, Subsonic protocol, DSP filters, and Radio endpoints.
pub fn configure(cfg: &mut web::ServiceConfig) {
    cfg.route(
        "/api/v2/audio/normalize",
        web::post().to(audio_normalize_handler),
    )
    .route(
        "/api/v2/audio/filter/eq",
        web::post().to(audio_eq_filter_handler),
    )
    .route(
        "/api/v2/audio/waveform",
        web::post().to(audio_waveform_handler),
    )
    .route(
        "/api/v2/audio/crossfade",
        web::post().to(audio_crossfade_handler),
    )
    .route(
        "/api/v2/audio/compress/flac",
        web::post().to(audio_flac_compress_handler),
    )
    .route(
        "/api/v2/audio/lyrics/parse",
        web::post().to(audio_lyrics_parse_handler),
    )
    .route(
        "/api/v2/audio/lyrics/current",
        web::get().to(audio_lyrics_current_handler),
    )
    .route(
        "/api/v2/audio/chapters/{id}",
        web::get().to(audio_chapters_handler),
    )
    .route(
        "/api/v2/audio/comments",
        web::post().to(audio_add_comment_handler),
    )
    .route(
        "/api/v2/audio/comments/{asset_id}",
        web::get().to(audio_get_comments_handler),
    )
    .route(
        "/api/v2/audio/bookmark",
        web::post().to(audio_save_bookmark_handler),
    )
    .route(
        "/api/v2/audio/bookmark/{user_id}/{asset_id}",
        web::get().to(audio_get_bookmark_handler),
    )
    .route(
        "/api/v2/audio/recommend/{user_id}",
        web::get().to(audio_recommend_handler),
    )
    .route(
        "/api/v2/audio/sleep/soundboard",
        web::post().to(audio_sleep_soundboard_handler),
    )
    .route(
        "/api/v2/audio/sleep/timer",
        web::post().to(audio_sleep_timer_handler),
    )
    .route(
        "/api/v2/audio/music/info",
        web::get().to(audio_music_info_handler),
    )
    .route(
        "/api/v2/audio/radio/live.m3u8",
        web::get().to(audio_radio_hls_handler),
    )
    .route(
        "/api/v2/audio/radio/listeners",
        web::get().to(audio_radio_listeners_handler),
    )
    .route(
        "/api/v2/audio/radio/chat",
        web::post().to(audio_radio_send_chat_handler),
    )
    .route(
        "/api/v2/audio/radio/chat",
        web::get().to(audio_radio_get_chat_handler),
    )
    .route(
        "/api/v2/audio/radio/heartbeat",
        web::post().to(audio_radio_heartbeat_handler),
    );
}
